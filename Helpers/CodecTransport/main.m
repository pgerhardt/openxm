static AudioObjectPropertyAddress Property(AudioObjectPropertySelector selector) {
    return (AudioObjectPropertyAddress){selector, kAudioObjectPropertyScopeGlobal, kAudioObjectPropertyElementMain};
}
static AudioObjectID FindOutput(NSString *uid) {
    if (!uid.length) return kAudioObjectUnknown;
    AudioObjectPropertyAddress p = Property(kAudioHardwarePropertyTranslateUIDToDevice);
    CFStringRef value = (__bridge CFStringRef)uid;
    AudioObjectID device = kAudioObjectUnknown; UInt32 size = sizeof(device);
    if (AudioObjectGetPropertyData(kAudioObjectSystemObject, &p, sizeof(value), &value, &size, &device) != noErr) return 0;
    p = Property(kAudioDevicePropertyStreams); p.mScope = kAudioObjectPropertyScopeOutput;
    if (AudioObjectGetPropertyDataSize(device, &p, 0, NULL, &size) != noErr || !size) return 0;
    return device;
}
static void Emit(NSDictionary *event) {
    NSData *data = [NSJSONSerialization dataWithJSONObject:event options:NSJSONWritingSortedKeys error:nil];
    if (!data) return;
    fwrite(data.bytes, 1, data.length, stdout); fputc('\n', stdout); fflush(stdout);
}
static NSArray<NSString *> *CodecIDs(void) { return @[@"sbc", @"aac", @"aptx", @"aptx-hd", @"ldac"]; }

// The custom transport owns AVRCP, so user-issued headset playback commands
// must reach the Mac's current player here. Command mapping follows Blue Bloom
// App/Sources/Services/Services.swift (MIT, pinned in OPENXM-PROVENANCE.md).
// No command is generated by connecting, selecting a codec or polling status.
static void ForwardPlaybackButton(uint8_t operation) {
    uint32_t command;
    switch (operation) {
        case 0x44: command = 0; break; // play
        case 0x46: command = 1; break; // pause
        case 0x45: command = 3; break; // stop
        case 0x4B: command = 4; break; // next
        case 0x4C: command = 5; break; // previous
        default: return;
    }
    static BOOL (*sendCommand)(uint32_t, CFDictionaryRef);
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        void *library = dlopen("/System/Library/PrivateFrameworks/MediaRemote.framework/MediaRemote", RTLD_LAZY);
        if (library) sendCommand = dlsym(library, "MRMediaRemoteSendCommand");
    });
    BOOL sent = sendCommand && sendCommand(command, NULL);
    BBLog(@"User playback button 0x%02x forwarded to macOS: %@", operation, sent ? @"yes" : @"no");
    if (!sent) Emit(@{@"event": @"warning", @"message": @"The Mac did not accept the headphone playback button. Use the player's controls."});
}

static void ClearHardwareVolume(void) {
    // This touches only OpenXM's virtual device, never the fallback's volume.
    CodecHALVolumeDevice *volume = [CodecHALVolumeDevice new];
    if ([volume attachWithChangeHandler:^{}]) [volume setHardwareMode:NO];
    [volume detach];
}
static NSTimeInterval RouteTime(void) { return NSProcessInfo.processInfo.systemUptime; }

@interface CodecSession : NSObject
@property A2DPSource *source;
@property NSString *requested;
@property NSString *journal;
@property CodecAudioRoute *route;
@property CodecHALAudioOutputs *outputs;
@property NSString *failure;
@property LinkStatus status;
@property BOOL stopping;
@property BOOL configuring;
@property CodecVolumeSync *volumeSync;
@property BOOL volumeDeadlineArmed;
@property CodecStreamSettings *settings;
@property NSTimer *timer;
@property NSTimeInterval shutdownDeadline;
@property CodecDisconnectPause *disconnectPause;
- (void)startAddress:(NSString *)address;
- (void)stop;
- (void)command:(NSDictionary *)command;
- (void)beginShutdown;
- (void)finishRecovery;
@end

@implementation CodecSession
- (CodecOptions *)options {
    return [self.settings optionsForCodec:self.requested];
}
- (void)report {
    if (self.configuring && (self.status == LinkStatusStreaming || self.status == LinkStatusIdle) &&
        [self.settings matchesConfiguration:self.source.configuration codec:self.requested]) self.configuring = NO;
    BOOL ready = !self.stopping && !self.configuring &&
        (self.status == LinkStatusStreaming || self.status == LinkStatusIdle);
    if (ready && self.volumeSync.ready) [self.route confirmReady];
    CodecConfiguration *config = ready ? self.source.configuration : nil;
    NSMutableDictionary *event = [@{@"event": @"status", @"requested": self.requested, @"settingsRevision": @(self.settings.revision),
        @"phase": self.stopping ? @"stopping" : ready ? (self.status == LinkStatusIdle ? @"idle" : @"streaming") : @"connecting",
        @"routed": @(self.route.taken && !self.route.relinquished && [[self.outputs currentOutputUID] isEqual:VirtualDeviceUID]),
        @"recentKbps": @(ready ? self.source.recentKbps : 0),
        @"targetKbps": @(ready ? self.source.targetKbps : 0),
        @"volumeSynced": @(self.volumeSync.ready && !self.stopping),
        @"estimatedOutputDelayMs": @250} mutableCopy];
    if (config) { event[@"activeCodec"] = config.codec; event[@"sampleRate"] = @(config.sampleRate); }
    if (config && [config.codec isEqual:CodecIDLDAC]) {
        event[@"ldacQuality"] = config.parameters[@"quality"];
        event[@"fastRecovery"] = config.parameters[@"fastRecovery"];
    }
    if (self.volumeSync.ready && !self.stopping) event[@"volume"] = @(self.volumeSync.confirmedVolume);
    if (ready && self.source.headsetDelayMs > 0) event[@"headsetReportedDelayMs"] = @(self.source.headsetDelayMs);
    if (self.source.fallbackCodec) {
        event[@"fallbackCodec"] = self.source.fallbackCodec;
        event[@"fallbackReason"] = @(self.source.fallbackReason);
    }
    if (self.stopping && self.failure) event[@"message"] = self.failure;
    Emit(event);
}
- (void)startAddress:(NSString *)address {
    self.status = LinkStatusConnecting; self.configuring = YES;
    if ([[NSFileManager defaultManager] fileExistsAtPath:self.journal]) {
        Emit(@{@"event": @"error", @"message": @"An earlier audio session needs route recovery first."}); exit(2);
    }
    self.outputs = [CodecHALAudioOutputs new];
    self.route = [[CodecAudioRoute alloc] initWithOutputs:self.outputs journal:self.journal virtualUID:VirtualDeviceUID];
    if (![self.route prepare]) {
        Emit(@{@"event": @"error", @"message": @"Install the OpenXM audio driver and select a normal output before starting."}); exit(2);
    }
    [self.route beginTransitionAt:RouteTime() timeout:45];
    IOBluetoothDevice *device = [IOBluetoothDevice deviceWithAddressString:address];
    if (!device || !device.isPaired) {
        Emit(@{@"event": @"error", @"message": @"The selected headphones must already be paired with this Mac."}); exit(2);
    }
    self.source = [[A2DPSource alloc] initWithDevice:device mode:SourceModePlay rate:0 file:nil seconds:0 systemAudio:NO];
    self.source.useVirtualDevice = YES; self.source.options = self.options;
    self.source.desiredSampleRate = self.settings.sampleRate;
    self.source.returnToSystemWhenStopped = YES;
    __weak CodecSession *weak = self;
    self.volumeSync = [[CodecVolumeSync alloc] initWithDevice:[CodecHALVolumeDevice new]];
    self.volumeSync.sendVolumeHandler = ^BOOL(int volume, CodecVolumeReply reply) {
        return [weak.source setRemoteVolume:volume completion:reply];
    };
    self.volumeSync.failureHandler = ^(NSString *message) {
        CodecSession *s = weak; if (!s || s.stopping) return;
        s.failure = message; [s stop];
    };
    self.volumeSync.changedHandler = ^{
        CodecSession *s = weak; if (!s || s.stopping) return;
        [s report];
    };
    self.source.remoteVolumeHandler = ^(int volume) {
        CodecSession *s = weak;
        if (s && !s.stopping) [s.volumeSync remoteVolumeChanged:volume];
    };
    self.source.remoteOperationHandler = ^(uint8_t operation) {
        if (operation == 0x41 || operation == 0x42) [weak.volumeSync stepVolume:operation == 0x41 ? 1 : -1];
        else ForwardPlaybackButton(operation);
    };
    if (![self.volumeSync start]) {
        Emit(@{@"event": @"error", @"message": @"Could not prepare linked headphone volume. Check the OpenXM audio driver."}); exit(2);
    }
    self.source.capabilitiesHandler = ^BOOL(NSArray<RemoteCodec *> *codecs) {
        NSMutableArray *ids = [NSMutableArray array];
        for (RemoteCodec *codec in codecs) if (codec.codec && ![ids containsObject:codec.codec]) [ids addObject:codec.codec];
        Emit(@{@"event": @"capabilities", @"codecs": ids});
        if (![ids containsObject:weak.requested]) {
            weak.failure = @"The headphones did not advertise the selected codec.";
            return NO;
        }
        if (weak.settings.sampleRate > 0) {
            BOOL offered = NO;
            for (RemoteCodec *codec in codecs) if ([codec.codec isEqual:weak.requested] && [codec.sampleRates containsObject:@(weak.settings.sampleRate)]) offered = YES;
            if (!offered) { weak.failure = @"The headphones did not advertise the requested sample rate."; return NO; }
        }
        return YES;
    };
    self.source.statusHandler = ^(LinkStatus status, double rate, int battery) {
        CodecSession *s = weak; if (!s || s.stopping) return;
        s.status = status;
        if (status != LinkStatusStreaming && status != LinkStatusIdle) [s.route beginTransitionAt:RouteTime() timeout:35];
        if (status == LinkStatusStreaming || status == LinkStatusIdle) {
            s.configuring = ![s.settings matchesConfiguration:s.source.configuration codec:s.requested];
            if (!s.volumeDeadlineArmed) {
                s.volumeDeadlineArmed = YES;
                dispatch_after(dispatch_time(DISPATCH_TIME_NOW, 5 * NSEC_PER_SEC), dispatch_get_main_queue(), ^{
                    CodecSession *current = weak;
                    if (current && !current.stopping && !current.volumeSync.ready) {
                        current.failure = @"The headphones did not report their volume. Returning to Automatic.";
                        [current stop];
                    }
                });
            }
        }
        [s report];
    };
    self.source.stoppingHandler = ^(NSString *reason) {
        CodecSession *s = weak; if (!s) return;
        if (!s.stopping && !s.failure) s.failure = reason;
        [s beginShutdown];
    };
    self.source.terminationHandler = ^(int code) {
        CodecSession *s = weak; if (!s) return;
        [s beginShutdown]; [s.timer invalidate];
        [s finishRecovery];
    };
    // Notifications catch user changes promptly; the timer is also a fallback
    // for HAL implementations that miss a notification.
    [self.outputs startObserving:^{
        CodecSession *s = weak;
        if ([s.route observeOutputChange]) { [s.disconnectPause cancel]; if (!s.stopping) [s stop]; }
    }];
    self.timer = [NSTimer scheduledTimerWithTimeInterval:0.5 repeats:YES block:^(NSTimer *timer) {
        CodecSession *s = weak;
        if ([s.route observeOutputChange]) { [s.disconnectPause cancel]; if (!s.stopping) [s stop]; }
        [s.disconnectPause pollAt:RouteTime()];
        if ([s.route transitionExpiredAt:RouteTime()] && !s.stopping) {
            s.failure = @"The selected codec could not connect in time."; [s stop];
        }
        if (s.stopping && RouteTime() >= s.shutdownDeadline) {
            // Even a stuck native handback must not hold a silent output forever.
            [s.timer invalidate]; [s finishRecovery]; return;
        }
        [s report];
    }];
    // Protect the initial native-to-custom switch too. VolumeSync.start has
    // silenced the virtual device; claim it before bluetoothd disconnects the
    // native headphone output and would otherwise send sound to speakers.
    if (![self.route take]) {
        self.failure = @"Could not prepare the OpenXM audio output."; [self stop]; return;
    }
    [self report];
    [self.source start];
}
- (void)beginShutdown {
    if (self.shutdownDeadline) return;
    self.stopping = YES; self.shutdownDeadline = RouteTime() + 20;
    [self.volumeSync stop];
    if (self.failure && self.route.taken && ![self.route observeOutputChange]) {
        // Persist before asking the player: crash recovery must not bypass an
        // unfinished pause check and unexpectedly expose music through speakers.
        [self.route setPlaybackProtection:YES];
        self.disconnectPause = [CodecDisconnectPause bundled];
        [self.disconnectPause startAt:RouteTime()];
    }
    // Unexpected loss gets a short grace period. An explicit native handback
    // waits longer for the original Bluetooth output before using speakers.
    [self.route beginRecoveryAt:RouteTime() grace:self.failure ? 3 : 0 waitForOriginal:self.failure ? 3 : 10];
    [self report];
}
- (void)finishRecovery {
    if ([self.route observeOutputChange]) [self.disconnectPause cancel];
    [self.disconnectPause pollAt:RouteTime()];
    if (self.disconnectPause.pending) {
        [self report];
        dispatch_after(dispatch_time(DISPATCH_TIME_NOW, NSEC_PER_MSEC * 100), dispatch_get_main_queue(), ^{ [self finishRecovery]; });
        return;
    }
    if (self.disconnectPause) {
        // The child can also cancel because a HAL ownership read failed. Only
        // an observed output change authorizes treating cancellation as handoff.
        BOOL safe = self.disconnectPause.allowsRecovery &&
            (![self.disconnectPause.status isEqual:@"cancelled"] || self.route.relinquished);
        [self.route setPlaybackProtection:!safe];
    }
    CodecRouteResult outcome = [self.route recoverAt:RouteTime()];
    if (outcome == CodecRoutePending) {
        [self report];
        dispatch_after(dispatch_time(DISPATCH_TIME_NOW, NSEC_PER_MSEC * 250), dispatch_get_main_queue(), ^{ [self finishRecovery]; });
        return;
    }
    [self.outputs stopObserving];
    BOOL restored = outcome != CodecRouteFailed;
    ClearHardwareVolume();
    NSMutableDictionary *result = [@{@"event": @"stopped", @"routeRestored": @(restored)} mutableCopy];
    result[@"playbackBlocked"] = @(self.route.playbackBlocked);
    if (self.disconnectPause) result[@"playbackPause"] = self.disconnectPause.status;
    if (self.failure) result[@"message"] = self.failure;
    if (restored && self.route.restoredOutputName && (self.failure || self.route.usedFallback))
        result[@"message"] = [NSString stringWithFormat:@"%@ Using %@.", self.failure ?: @"The original audio output is unavailable.", self.route.restoredOutputName];
    if (!restored) result[@"message"] = @"Audio could not be restored. Choose an available output in Sound settings.";
    if (self.route.playbackBlocked) result[@"message"] = @"Could not confirm that media paused. Audio is kept silent. Pause your player, or restore audio anyway.";
    else if (restored && [self.disconnectPause.status isEqual:@"paused"] && self.route.restoredOutputName)
        result[@"message"] = [NSString stringWithFormat:@"Headphone audio stopped. Media paused; audio restored to %@.", self.route.restoredOutputName];
    Emit(result); exit(self.failure || !restored ? 1 : 0);
}
- (void)stop {
    if (self.stopping) return;
    [self beginShutdown];
    [self.source stopWithReason:@"OpenXM requested native audio" exitCode:0];
}
- (void)command:(NSDictionary *)command {
    if (![command isKindOfClass:NSDictionary.class]) return;
    if ([command[@"command"] isEqual:@"stop"]) {
        if ([command[@"unexpected"] isEqual:@YES] && !self.stopping && !self.failure) self.failure = @"The custom audio connection stopped responding.";
        [self stop]; return;
    }
    if ([command[@"command"] isEqual:@"volume"]) {
        NSNumber *volume = command[@"volume"];
        if (self.stopping || ![volume isKindOfClass:NSNumber.class] ||
            CFGetTypeID((__bridge CFTypeRef)volume) == CFBooleanGetTypeID() ||
            volume.doubleValue != volume.intValue || volume.intValue < 0 || volume.intValue > 127) return;
        if (![self.volumeSync setLocalVolume:volume.intValue] && !self.stopping)
            Emit(@{@"event": @"warning", @"message": @"Wait for headphone volume control to connect."});
        [self report]; return;
    }
    NSString *codec = command[@"codec"];
    if (![command[@"command"] isEqual:@"select"] || ![CodecIDs() containsObject:codec] || self.stopping) return;
    CodecStreamSettings *settings = [CodecStreamSettings fromDictionary:command[@"settings"]];
    if (!settings || settings.revision <= self.settings.revision) return;
    self.settings = settings;
    self.requested = codec; self.configuring = YES;
    [self.route beginTransitionAt:RouteTime() timeout:35];
    [self.source updateOptions:self.options desiredSampleRate:settings.sampleRate];
    [self report];
}
@end

int main(int argc, const char *argv[]) {
    @autoreleasepool {
        signal(SIGPIPE, SIG_IGN);
        BBLogSetSink(^(NSString *line) { fprintf(stderr, "%s\n", line.UTF8String); });
        NSArray<NSString *> *args = NSProcessInfo.processInfo.arguments;
        if (args.count == 2 && [args[1] isEqual:@"--inspect"]) {
            Emit(@{@"event": @"inspection", @"driverInstalled": @(FindOutput(VirtualDeviceUID) != 0), @"codecs": CodecIDs()}); return 0;
        }
        if ((args.count == 3 || (args.count == 4 && [args[3] isEqual:@"--allow-playing"])) && [args[1] isEqual:@"--recover"]) {
            // Use the same lock as --stream: a launch racing recovery cannot
            // acquire or lose ownership halfway through a route change.
            int lock = open([[args[2] stringByAppendingString:@".lock"] fileSystemRepresentation], O_CREAT | O_RDWR, 0600);
            if (lock < 0 || flock(lock, LOCK_EX | LOCK_NB) != 0) {
                Emit(@{@"event": @"recovery", @"routeRestored": @NO}); return 1;
            }
            BOOL hadJournal = [[NSFileManager defaultManager] fileExistsAtPath:args[2]];
            CodecAudioRoute *route = [[CodecAudioRoute alloc] initWithOutputs:[CodecHALAudioOutputs new] journal:args[2] virtualUID:VirtualDeviceUID];
            route.allowsUnpausedPlayback = args.count == 4;
            [route beginRecoveryAt:RouteTime() grace:0 waitForOriginal:0];
            BOOL restored = [route recoverAt:RouteTime()] != CodecRouteFailed;
            if (restored && hadJournal) ClearHardwareVolume();
            NSMutableDictionary *result = [@{@"event": @"recovery", @"routeRestored": @(restored)} mutableCopy];
            result[@"playbackBlocked"] = @(route.playbackBlocked);
            if (route.playbackBlocked) result[@"message"] = @"Media pause could not be confirmed. Audio is kept silent until you restore audio or choose an output.";
            if (restored && route.restoredOutputName) result[@"message"] = [NSString stringWithFormat:@"Audio recovered. Using %@.", route.restoredOutputName];
            Emit(result); return restored ? 0 : 1;
        }
        NSRegularExpression *addressPattern = [NSRegularExpression regularExpressionWithPattern:@"^([0-9a-fA-F]{2}[:-]){5}[0-9a-fA-F]{2}$" options:0 error:nil];
        if ((args.count != 5 && args.count != 6) || ![args[1] isEqual:@"--stream"] || ![CodecIDs() containsObject:args[3]] ||
            ![addressPattern numberOfMatchesInString:args[2] options:0 range:NSMakeRange(0, args[2].length)] || !args[4].isAbsolutePath) {
            fprintf(stderr, "Usage: OpenXMCodecTransport --inspect | --recover JOURNAL | --stream ADDRESS CODEC JOURNAL [SETTINGS_JSON]\n"); return 64;
        }
        CodecSession *session = [CodecSession new]; session.requested = args[3]; session.journal = args[4];
        session.settings = args.count == 6 ? [CodecStreamSettings fromDictionary:[NSJSONSerialization JSONObjectWithData:[args[5] dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil]] : CodecStreamSettings.defaults;
        if (!session.settings) { Emit(@{@"event": @"error", @"message": @"Invalid codec settings."}); return 64; }
        int lock = open([[args[4] stringByAppendingString:@".lock"] fileSystemRepresentation], O_CREAT | O_RDWR, 0600);
        if (lock < 0 || flock(lock, LOCK_EX | LOCK_NB) != 0) {
            Emit(@{@"event": @"error", @"message": @"Another codec session owns this audio route."}); return 2;
        }
        // SIGTERM and parent stdin EOF get the same orderly handback as Automatic.
        signal(SIGTERM, SIG_IGN); signal(SIGINT, SIG_IGN);
        dispatch_source_t term = dispatch_source_create(DISPATCH_SOURCE_TYPE_SIGNAL, SIGTERM, 0, dispatch_get_main_queue());
        dispatch_source_t interrupt = dispatch_source_create(DISPATCH_SOURCE_TYPE_SIGNAL, SIGINT, 0, dispatch_get_main_queue());
        dispatch_source_set_event_handler(term, ^{ [session stop]; }); dispatch_resume(term);
        dispatch_source_set_event_handler(interrupt, ^{ [session stop]; }); dispatch_resume(interrupt);
        dispatch_async(dispatch_get_global_queue(QOS_CLASS_UTILITY, 0), ^{
            char *line = NULL; size_t capacity = 0; ssize_t count;
            while ((count = getline(&line, &capacity, stdin)) > 0) {
                if (count > 16384) break;
                NSData *data = [NSData dataWithBytes:line length:(NSUInteger)count];
                NSDictionary *command = [NSJSONSerialization JSONObjectWithData:data options:0 error:nil];
                dispatch_async(dispatch_get_main_queue(), ^{ [session command:command]; });
            }
            free(line); dispatch_async(dispatch_get_main_queue(), ^{ [session stop]; });
        });
        [session startAddress:args[2]];
        [[NSRunLoop mainRunLoop] run];
    }
    return 0;
}
