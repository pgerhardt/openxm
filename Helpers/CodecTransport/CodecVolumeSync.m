#import "CodecVolumeSync.h"
#import <CoreAudio/CoreAudio.h>
#import "VirtualDeviceProtocol.h"
#include <math.h>

@implementation CodecVolumeSync {
    id<CodecVolumeDevice> _device;
    BOOL _started;
    BOOL _inFlight;
    int _displayed;
    int _desired;
    NSUInteger _generation;
}
- (instancetype)initWithDevice:(id<CodecVolumeDevice>)device {
    if ((self = [super init])) {
        _device = device; _confirmedVolume = -1; _displayed = -1; _desired = -1;
    }
    return self;
}
- (BOOL)start {
    [self stop];
    __weak CodecVolumeSync *weak = self;
    if (![_device attachWithChangeHandler:^{ [weak localVolumeChanged]; }]) return NO;
    // No media is routed here yet. A previous helper may have exited in hardware
    // mode; clear that state and silence this unused output until Sony replies.
    _displayed = 0;
    if (![_device setHardwareMode:NO] || ![_device setScalar:0]) { [_device detach]; return NO; }
    _started = YES;
    return YES;
}
- (void)fail:(NSString *)message {
    [self stop];
    if (_failureHandler) _failureHandler(message);
}
- (BOOL)display:(int)volume {
    _displayed = volume; // Suppress the HAL notification generated by our own write.
    if (![_device setScalar:volume / 127.0f]) {
        [self fail:@"Could not synchronize the Mac volume with the headphones."];
        return NO;
    }
    return YES;
}
- (void)remoteVolumeChanged:(int)volume {
    if (!_started) return;
    if (volume < 0 || volume > 127) {
        [self fail:@"Headphone volume control disconnected. Returning to Automatic."]; return;
    }
    _confirmedVolume = volume;
    if (!_ready) {
        // Never transmit the remembered Mac slider value (often 100%) on connect.
        if (![self display:volume]) return;
        if (![_device setHardwareMode:YES]) {
            [self fail:@"The audio driver could not enable linked headphone volume."]; return;
        }
        _ready = YES;
    } else if (!_inFlight && _desired < 0 && ![self display:volume]) { return; }
    if (_changedHandler) _changedHandler();
}
- (void)localVolumeChanged {
    if (!_ready || !_started) return;
    float scalar;
    if (![_device readScalar:&scalar] || !isfinite(scalar) || scalar < 0 || scalar > 1) {
        [self fail:@"Could not read the Mac volume control."]; return;
    }
    int volume = (int)lroundf(scalar * 127);
    if (volume == _displayed) return;
    _displayed = volume;
    _desired = volume;
    [self sendNext];
}
- (void)sendNext {
    if (!_ready || !_started || _inFlight || _desired < 0) return;
    int volume = _desired; _desired = -1;
    if (volume == _confirmedVolume) { [self display:volume]; return; }
    _inFlight = YES;
    NSUInteger generation = _generation;
    __weak CodecVolumeSync *weak = self;
    BOOL sent = _sendVolumeHandler && _sendVolumeHandler(volume, ^(BOOL accepted, int actual) {
        CodecVolumeSync *s = weak;
        if (!s || !s->_started || generation != s->_generation) return;
        s->_inFlight = NO;
        if (!accepted || actual < 0 || actual > 127) {
            [s fail:@"The headphones did not confirm the volume change. Returning to Automatic."]; return;
        }
        s->_confirmedVolume = actual;
        // Coalesce slider movement while awaiting a reply; never replay stale
        // intermediate levels or treat a sent command as an accepted volume.
        if (s->_desired >= 0) [s sendNext];
        else if (![s display:actual]) return;
        if (s->_changedHandler) s->_changedHandler();
    });
    if (!sent && _started) [self fail:@"Headphone volume control is unavailable. Returning to Automatic."];
}
- (BOOL)setLocalVolume:(int)volume {
    if (!_ready || !_started || volume < 0 || volume > 127) return NO;
    // App changes enter the same HAL -> acknowledged AVRCP path as the Mac
    // slider. Sony's separate MDR volume SET is ignored in this custom session.
    if (![_device setScalar:volume / 127.0f]) {
        [self fail:@"Could not change the linked headphone volume."]; return NO;
    }
    [self localVolumeChanged];
    return _ready;
}
- (void)stepVolume:(int)direction {
    if (!_ready || (direction != -1 && direction != 1)) return;
    float scalar;
    if (![_device readScalar:&scalar] || !isfinite(scalar)) return;
    if (![_device setScalar:fmaxf(0, fminf(1, scalar + direction / 16.0f))]) {
        [self fail:@"Could not change the linked headphone volume."]; return;
    }
    [self localVolumeChanged];
}
- (void)stop {
    _generation++; _ready = NO; _started = NO; _inFlight = NO;
    _desired = -1; _confirmedVolume = -1; _displayed = -1;
    [_device setHardwareMode:NO];
    [_device detach];
}
- (void)dealloc { [_device setHardwareMode:NO]; [_device detach]; }
@end

static AudioObjectPropertyAddress GlobalProperty(AudioObjectPropertySelector selector) {
    return (AudioObjectPropertyAddress){selector, kAudioObjectPropertyScopeGlobal, kAudioObjectPropertyElementMain};
}
@implementation CodecHALVolumeDevice {
    AudioObjectID _device;
    AudioObjectID _control;
    AudioObjectPropertyListenerBlock _listener;
}
- (BOOL)attachWithChangeHandler:(void (^)(void))handler {
    [self detach];
    AudioObjectPropertyAddress p = GlobalProperty(kAudioHardwarePropertyTranslateUIDToDevice);
    CFStringRef uid = CFSTR(kBBDeviceUID);
    UInt32 size = sizeof(_device);
    if (AudioObjectGetPropertyData(kAudioObjectSystemObject, &p, sizeof(uid), &uid, &size, &_device) != noErr || !_device) return NO;
    p = GlobalProperty(kAudioObjectPropertyOwnedObjects);
    AudioObjectID objects[32]; size = sizeof(objects);
    if (AudioObjectGetPropertyData(_device, &p, 0, NULL, &size, objects) != noErr) return NO;
    for (UInt32 i = 0; i < size / sizeof(AudioObjectID); i++) {
        AudioObjectPropertyAddress type = GlobalProperty(kAudioObjectPropertyClass);
        AudioClassID value = 0; UInt32 bytes = sizeof(value);
        if (AudioObjectGetPropertyData(objects[i], &type, 0, NULL, &bytes, &value) == noErr && value == kAudioVolumeControlClassID) {
            _control = objects[i]; break;
        }
    }
    if (!_control) return NO;
    _listener = ^(UInt32 count, const AudioObjectPropertyAddress *addresses) { handler(); };
    p = GlobalProperty(kAudioLevelControlPropertyScalarValue);
    if (AudioObjectAddPropertyListenerBlock(_control, &p, dispatch_get_main_queue(), _listener) != noErr) {
        [self detach]; return NO;
    }
    return YES;
}
- (BOOL)readScalar:(float *)value {
    if (!_control) return NO;
    AudioObjectPropertyAddress p = GlobalProperty(kAudioLevelControlPropertyScalarValue);
    UInt32 size = sizeof(*value);
    return AudioObjectGetPropertyData(_control, &p, 0, NULL, &size, value) == noErr;
}
- (BOOL)setScalar:(float)value {
    if (!_control || !isfinite(value) || value < 0 || value > 1) return NO;
    AudioObjectPropertyAddress p = GlobalProperty(kAudioLevelControlPropertyScalarValue);
    return AudioObjectSetPropertyData(_control, &p, 0, NULL, sizeof(value), &value) == noErr;
}
- (BOOL)setHardwareMode:(BOOL)enabled {
    if (!_device) return !enabled;
    AudioObjectPropertyAddress p = GlobalProperty(kBBPropertyHardwareVolume);
    CFNumberRef number = (__bridge CFNumberRef)@(enabled ? 1 : 0);
    return AudioObjectSetPropertyData(_device, &p, 0, NULL, sizeof(number), &number) == noErr;
}
- (void)detach {
    if (_listener && _control) {
        AudioObjectPropertyAddress p = GlobalProperty(kAudioLevelControlPropertyScalarValue);
        AudioObjectRemovePropertyListenerBlock(_control, &p, dispatch_get_main_queue(), _listener);
    }
    _listener = nil; _control = 0; _device = 0;
}
- (void)dealloc { [self detach]; }
@end
